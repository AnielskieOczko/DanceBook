/**
 * Draws the two charts on the training statistics page.
 *
 * Both datasets arrive as JSON on the canvas elements themselves, colours included.
 * Slices carry design token custom properties (var(--color-...)) which this script
 * resolves at runtime via getComputedStyle so Chart.js can draw to canvas while the
 * stylesheet remains the single source of truth.
 */
(function () {
    function readSlices(canvas) {
        try {
            return JSON.parse(canvas.dataset.slices || '[]');
        } catch (error) {
            console.error('[training-stats] could not read chart data', error);
            return [];
        }
    }

    /**
     * Canvas 2D cannot resolve CSS custom properties (var(--x)), so resolve
     * tokens at runtime against computed style on :root or canvas before drawing.
     */
    function resolveColor(canvas, color) {
        if (!color || typeof color !== 'string') return color;
        var trimmed = color.trim();
        if (trimmed.indexOf('var(') === 0) {
            var match = trimmed.match(/^var\(\s*([^,\)\s]+)/);
            if (match) {
                var propName = match[1];
                var computed = getComputedStyle(canvas || document.documentElement).getPropertyValue(propName).trim();
                if (computed) return computed;
            }
        }
        return color;
    }

    /**
     * Chart.js hands the callback an index, not our slice. Closing over the array keeps
     * the pre-formatted duration reachable without hanging a custom property off Chart's
     * own data object, which it makes no promise to preserve.
     */
    function tooltipLabelFor(slices) {
        return function (context) {
            var slice = slices[context.dataIndex];
            return ' ' + slice.label + ': ' + slice.durationLabel;
        };
    }

    function drawCategoryChart(canvas) {
        var slices = readSlices(canvas);
        if (slices.length === 0) return;

        new Chart(canvas, {
            type: 'doughnut',
            data: {
                labels: slices.map(function (slice) { return slice.label; }),
                datasets: [{
                    data: slices.map(function (slice) { return slice.minutes; }),
                    backgroundColor: slices.map(function (slice) { return resolveColor(canvas, slice.color); }),
                    borderWidth: 0
                }]
            },
            options: {
                responsive: true,
                maintainAspectRatio: false,
                cutout: '62%',
                plugins: {
                    // The template renders the legend as a list, which screen readers can
                    // reach and which survives JavaScript being switched off.
                    legend: { display: false },
                    tooltip: { callbacks: { label: tooltipLabelFor(slices) } }
                }
            }
        });
    }

    function drawEventTypeChart(canvas) {
        var slices = readSlices(canvas);
        if (slices.length === 0) return;

        var gridColor = resolveColor(canvas, canvas.dataset.gridColor);

        new Chart(canvas, {
            type: 'bar',
            data: {
                labels: slices.map(function (slice) { return slice.label; }),
                datasets: [{
                    data: slices.map(function (slice) { return slice.minutes; }),
                    backgroundColor: slices.map(function (slice) { return resolveColor(canvas, slice.color); }),
                    borderRadius: 4
                }]
            },
            options: {
                indexAxis: 'y',
                responsive: true,
                maintainAspectRatio: false,
                scales: {
                    x: {
                        ticks: {
                            // Axis tick values are generated by Chart.js at runtime and have no
                            // server-side counterpart. Unlike slice durations (which come from
                            // durationLabel), these numbers cannot be pre-computed. This is the
                            // sole exception to the constraint that formatting lives server-side.
                            callback: function (value) {
                                return value >= 60 ? (value / 60) + 'h' : value + 'm';
                            }
                        },
                        grid: { color: gridColor }
                    },
                    y: { grid: { display: false } }
                },
                plugins: {
                    legend: { display: false },
                    tooltip: { callbacks: { label: tooltipLabelFor(slices) } }
                }
            }
        });
    }

    document.addEventListener('DOMContentLoaded', function () {
        var categoryCanvas = document.getElementById('category-chart');
        if (categoryCanvas) drawCategoryChart(categoryCanvas);

        var eventTypeCanvas = document.getElementById('event-type-chart');
        if (eventTypeCanvas) drawEventTypeChart(eventTypeCanvas);
    });
})();
